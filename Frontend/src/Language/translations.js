export function isSupportedUILanguage(
  code
) {

  return UI_LANGUAGES.some(
    (language) =>
      language.code === code
  );

}


export function getUILanguage(
  code
) {

  return (
    UI_LANGUAGES.find(
      (language) =>
        language.code === code
    )
    ||
    UI_LANGUAGES.find(
      (language) =>
        language.code === DEFAULT_UI_LANGUAGE
    )
    ||
    UI_LANGUAGES[0]
  );

}